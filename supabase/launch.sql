-- The SAST day, and the Monday of the SAST week, of "now".
create or replace function public.sast_day() returns date language sql stable as $$ select (now() at time zone 'Africa/Johannesburg')::date $$;
create or replace function public.sast_week() returns date language sql stable as $$ select date_trunc('week', now() at time zone 'Africa/Johannesburg')::date $$;

-- Weeks that have finished (and are not before the first badge week) give their top 3 on each board a badge.
create or replace function public.close_finished_weeks() returns void language plpgsql security definer set search_path = public as $$
declare w date; first_week date; b text;
begin
  select value::date into first_week from score_config where key = 'first_badge_week';
  for w in
    select distinct week from activity_log
    where week < sast_week() and week >= coalesce(first_week, '2100-01-01') and points > 0
      and week not in (select week from score_weeks_closed)
  loop
    foreach b in array array['academics', 'social', 'sport'] loop
      insert into score_badges (week, board, rank, player, points)
      select w, b, t.rank, t.player, t.pts from (
        select player, sum(points)::int as pts, row_number() over (order by sum(points) desc, max(at) asc)::int as rank
        from activity_log where week = w and board = b and points > 0 group by player
      ) t where t.rank <= 3
      on conflict do nothing;
    end loop;
    insert into score_weeks_closed (week) values (w) on conflict do nothing;
  end loop;
end $$;

-- Log (and score) one finished activity. Returns { ok, scored, points, board, used, limit, reason }.
create or replace function public.record_activity(
  p_id text, p_secret text, p_event text, p_activity text, p_place text, p_category text, p_client_at timestamptz,
  p_name text default null, p_handle text default null, p_house text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  rule score_rules%rowtype;
  d date := sast_day();
  w date := sast_week();
  used int := 0;
  pts int := 0;
  brd text := null;
  nm text := left(coalesce(p_name, ''), 24);
  today int;
begin
  if p_id is null or length(p_id) not between 8 and 64 or p_secret is null or length(p_secret) < 16
     or p_event is null or length(p_event) not between 6 and 40
     or p_activity is null or p_activity !~ '^[a-z0-9_]{1,40}$' then
    raise exception 'bad activity';
  end if;
  perform pg_advisory_xact_lock(hashtext(p_id));
  -- the name on the board is cleaned like chat (a slur: the name becomes Student)
  begin
    nm := public.clean_chat_body(nm);
  exception when others then
    nm := 'Student';
  end;
  insert into score_players (id, secret_hash, name, handle, house)
  values (p_id, md5(p_secret), nm, left(coalesce(p_handle, ''), 20), left(coalesce(p_house, ''), 40))
  on conflict (id) do nothing;
  if (select secret_hash from score_players where id = p_id) <> md5(p_secret) then raise exception 'not you'; end if;
  update score_players set name = nm, handle = left(coalesce(p_handle, ''), 20), house = left(coalesce(p_house, ''), 40), seen_at = now() where id = p_id;
  if exists (select 1 from activity_log where event = p_event) then return jsonb_build_object('ok', true, 'dup', true); end if;
  select count(*) into today from activity_log where player = p_id and day = d;
  if today >= 600 then return jsonb_build_object('ok', false, 'reason', 'too_many'); end if;
  select * into rule from score_rules where activity_id = p_activity;
  if found then
    select count(*) into used from activity_log where player = p_id and day = d and activity = p_activity and points > 0;
    if used < rule.daily_limit then pts := rule.points; brd := rule.board; used := used + 1; end if;
  end if;
  insert into activity_log (event, player, activity, place, category, client_at, day, week, board, points)
  values (p_event, p_id, p_activity, left(p_place, 40), left(p_category, 20), p_client_at, d, w, brd, pts);
  perform close_finished_weeks();
  return jsonb_build_object('ok', true, 'scored', pts > 0, 'points', pts, 'board', rule.board,
    'used', used, 'limit', rule.daily_limit,
    'reason', case when rule.activity_id is null then 'no_score' when pts = 0 then 'daily_limit' else 'ok' end);
end $$;
grant execute on function public.record_activity(text, text, text, text, text, text, timestamptz, text, text, text) to anon, authenticated;

-- This week's top 10 on a board, and where p_id stands.
create or replace function public.score_board(p_board text, p_id text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare w date := sast_week(); top jsonb; you jsonb;
begin
  if p_board not in ('academics', 'social', 'sport') then raise exception 'unknown board'; end if;
  perform close_finished_weeks();
  with ranked as (
    select player, sum(points)::int as pts, (row_number() over (order by sum(points) desc, max(at) asc))::int as rank
    from activity_log where week = w and board = p_board and points > 0 group by player
  )
  select
    coalesce((select jsonb_agg(jsonb_build_object('rank', r.rank, 'name', coalesce(nullif(p.name, ''), 'Student'), 'handle', coalesce(p.handle, ''),
        'house', coalesce(p.house, ''), 'points', r.pts, 'you', r.player = p_id) order by r.rank)
      from ranked r left join score_players p on p.id = r.player where r.rank <= 10), '[]'::jsonb),
    (select jsonb_build_object('rank', r.rank, 'points', r.pts) from ranked r where r.player = p_id)
  into top, you;
  return jsonb_build_object('week', w, 'top', top, 'you', you);
end $$;
grant execute on function public.score_board(text, text) to anon, authenticated;

-- The badges a player won in weeks gone by.
create or replace function public.my_badges(p_id text)
returns jsonb language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(jsonb_build_object('week', week, 'board', board, 'rank', rank) order by week, board), '[]'::jsonb)
  from score_badges where player = p_id
$$;
grant execute on function public.my_badges(text) to anon, authenticated;

-- Errors and funnel events (src/errors.js, src/events.js): who sent it, and a limit per player per hour.
alter table public.client_errors add column if not exists player text;
create index if not exists client_errors_player_idx on public.client_errors (player, created_at desc);
-- (security definer: the player who sends cannot read the table, but the count must see every row)
create or replace function public.client_errors_limit() returns trigger language plpgsql security definer set search_path = public as $$
declare is_funnel boolean := coalesce(new.kind, '') = 'funnel'; cap int; sent int;
begin
  if new.player is not null then
    cap := case when is_funnel then 40 else 20 end;
    select count(*) into sent from public.client_errors
      where player = new.player and (kind = 'funnel') = is_funnel and created_at > now() - interval '1 hour';
    if sent >= cap then
      return null; -- over the limit: the row is quietly dropped
    end if;
  end if;
  return new;
end $$;
drop trigger if exists client_errors_limit_trg on public.client_errors;
create trigger client_errors_limit_trg before insert on public.client_errors for each row execute function public.client_errors_limit();

