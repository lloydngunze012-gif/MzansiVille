-- safely (create ... if not exists / or replace), also after `npm run scores-sql` changes the rules.
-- Needs the base schema (public.is_admin(), public.client_errors, public.clean_chat_body()) already in place.
--
-- Until it is run the game plays on: activities are counted on the phone and kept to send later, the
-- leaderboard says "opens soon", and the Feedback button files its text in client_errors.
--   * activity_log: EVERY finished activity of every player (activity, place, category, day), one row each.
--   * score_rules: which activities score on Academics, Social or Sport, how many points, and the DAILY LIMIT
--     per player. Generated from data/campusville/leaderboard.json by `npm run scores-sql` (do not edit by hand).
--   * record_activity(): the only way to log or score. It knows who you are (your phone's secret, the way cards
--     work), applies the daily limit with the SERVER's clock (Africa/Johannesburg days), and cannot be given
--     more points by a changed client. No table can be written to directly (there are no insert policies).
--   * score_board(): top 10 of a board this week plus your own rank. A week runs Monday 00:00 SAST to Sunday.
--   * The top 3 of each board keep a badge: score_badges is filled when a week has finished (the first call
--     after Monday 00:00 SAST closes it), only for weeks from score_config 'first_badge_week'.
--   * client_errors gets a player column and a limit: 20 errors and 40 funnel events per player per hour.
--   * feedback: the menu's Feedback button and the third-session "How's it going?" pop-up.
-- ---------------------------------------------------------------------------

