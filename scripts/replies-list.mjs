// Writes docs/sprints/actions/replies.md: every conversation reply in the game
// (people.json, the crush arc) and every lecture and morning choice, with what it does.
// Run: node scripts/replies-list.mjs
import fs from 'node:fs'

const people = JSON.parse(fs.readFileSync('data/campusville/people.json', 'utf8'))
const lecture = JSON.parse(fs.readFileSync('data/campusville/day1_lecture.json', 'utf8'))

const DOES = {
  bye: 'Their answer, then one "Bye" button: the chat ends, they wave, you walk a few steps away.',
  eat: 'You both walk to the caf queue (they walk behind you), the line moves, Auntie Pinky\'s menu opens at the front, you pay, then sit at one table and eat together (+Social, closer).',
  study: 'You both walk to the library, go in, sit at the desks and study together (+Grades, +Social, closer).',
  sit: 'A bench right there: you both sit and chat (+Social, closer).',
  walk: 'You walk together to your lecture venue (if it is next) or across campus, chatting on the way (+Social, closer).',
  swap: 'You swap numbers: they go in your phone, with a "See your phone" button that opens it.',
  order: 'Her menu opens: pick an item (and a size), pay, then "Sit and eat" or "Take it to go".',
  consult: 'A consultation scene with the lecturer about chapter one (+3 Grades).',
  talk: 'Their answer with what it changed (Social, closer or cooler), then the things you can do together, "Keep talking" or "Bye" (walks you off).',
}
const crushActs = { eat: 'eat (to Mam\' Gugu if it is a vetkoek, else the caf)' }

const rows = []
for (const group of ['people', 'archetypes']) {
  for (const [id, p] of Object.entries(people[group])) {
    const who = group === 'people' ? `${p.name || id}` : `Student (${id})`
    p.chats.forEach((chat, i) => {
      const when = i === 0 ? 'first chat' : i === 1 ? 'second chat' : 'later chats'
      for (const r of chat.replies) rows.push([who, when, r.text, r.act || 'talk'])
    })
  }
}

// The crush arc's replies (src/engine/crush-arc.js), read from the source.
const arc = fs.readFileSync('src/engine/crush-arc.js', 'utf8')
const crush = [...arc.matchAll(/R\('((?:[^'\\]|\\.)*)', [^)]*?(?:, '(\w+)')?\)/g)].map((m) => [m[1].replace(/\\'/g, '\''), m[2] || 'talk'])

const counts = {}
for (const r of rows) counts[r[3]] = (counts[r[3]] || 0) + 1
for (const r of crush) counts[r[1]] = (counts[r[1]] || 0) + 1

let md = `# Every conversation reply and what it does (A6)

Generated by \`node scripts/replies-list.mjs\` from data/campusville/people.json, src/engine/crush-arc.js and data/campusville/day1_lecture.json.

Every reply is one of these. None is a dead end: each leads to an action you see, a result, or a clear goodbye.

| Leads to | What happens | Replies |
|---|---|---|
${Object.keys(DOES).map((k) => `| **${k}** | ${DOES[k]} | ${counts[k] || 0} |`).join('\n')}

The talk card's action buttons (students): "Let's get something to eat" (eat), "Let's study" (study), "Sit with them" (sit), "Walk with me" (walk), "Swap numbers" (swap). Vendors: "I'd like to order" (order). Lecturers: "Can I ask about chapter one?" (consult). "Walk away" (no reply) ends the chat and walks you off.

## People and students (${rows.length} replies)

| Who | When | Reply | Leads to |
|---|---|---|---|
${rows.map((r) => `| ${r[0]} | ${r[1]} | ${r[2].replace(/\|/g, '/')} | ${r[3]} |`).join('\n')}

## The one from the bus stop (crush arc, ${crush.length} replies)

| Reply | Leads to |
|---|---|
${crush.map((r) => `| ${r[0]} | ${crushActs[r[1]] || r[1]} |`).join('\n')}

## Morning choices (src/world/morning.js)

Every choice plays out in the room or on the way; none is a stat jump.

| Choice | What happens |
|---|---|
| Snooze 10 min / Get up | Snooze: the clock rolls 10 minutes and the roommate comments. Get up: you sit up on the bed, stretch, stand. |
| Noodles in res | You walk to the kettle and cook (or the roommate takes the last packet, and you choose again). |
| Tuck shop on the way | You walk out the door to the tuck shop (R12). |
| Caf breakfast on campus | You head to campus and eat at the caf (R30). |
| Walk to the bus hungry | You leave now, hungry (-15 Fullness). |
| Walk to the bus / Skip to campus | Walk: the walk to the bus stop, where the meet-cute happens. Skip: straight to the gate, same time. |
| Say something funny / Ask about the bus / Put on headphones | Each plays a different meet-cute line and reply; asking about the bus can tell you their name. |
| Next to them / Window seat at the back | You sit in that seat on the bus; the ride plays from there. |

## Lecture choices (data/campusville/day1_lecture.json)

| Choice | What happens |
|---|---|
${lecture.find_seat.options.map((o) => `| Seat: ${o.label} | You walk up the aisle and sit there; ${(o.line || '').replace(/\|/g, '/')} |`).join('\n')}
${lecture.moments.flatMap((m) => m.choices.map((c) => `| ${m.title}: ${c.label} | The result plays out (${c.outcomes.map((o) => o.tone).join(' / ')}), with what it changed floating up. |`)).join('\n')}
`
fs.writeFileSync('docs/sprints/actions/replies.md', md)
console.log(`replies.md: ${rows.length} people replies, ${crush.length} crush replies`, counts)
