import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseCsv, num } from '../src/engine/csv.js'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const district = 'campusville'
const data = join(root, 'data', district)

function sql(value) {
  if (value == null || value === '') return 'null'
  return `'${String(value).replace(/'/g, "''")}'`
}

function rows(file) {
  return parseCsv(readFileSync(join(data, file), 'utf8'))
}

const places = rows('places.csv')
const activities = rows('activities.csv')
const residences = rows('residences.csv').filter((row) => row.name && !row.name.startsWith('ADD '))
const events = JSON.parse(readFileSync(join(data, 'events.json'), 'utf8'))

const placeSql = places.map((row) =>
  `(${sql(district)}, ${sql(row.id)}, ${sql(row.name)}, ${sql(row.kind)}, ${num(row.x)}, ${num(row.y)}, ${sql(row.what_happens_here)})`).join(',\n')

const activitySql = activities.map((row) =>
  `(${sql(district)}, ${sql(row.id)}, ${sql(row.phase)}, ${sql(row.place_id)}, ${sql(row.name)}, ${num(row.money)}, ${num(row.energy)}, ${num(row.grades)}, ${num(row.social)}, ${num(row.hunger)}, ${num(row.time_slots)}, ${sql(row.risk_or_twist)})`).join(',\n')

const residenceSql = residences.map((row) =>
  `(${sql(district)}, ${sql(row.name)}, ${sql(row.type)}, ${row.distance_km === '' ? 'null' : num(row.distance_km)}, ${sql(row.notes)})`).join(',\n')

const eventSql = events.map((event) =>
  `(${sql(district)}, ${sql(event.id)}, ${sql(event.title)}, ${sql(event.text)}, ${sql(JSON.stringify(event.choices))}::jsonb)`).join(',\n')

const sqlText = `-- Generated by scripts/seed.mjs from /data/${district}. Safe to re-run.
delete from public.district_activities where district_id = ${sql(district)};
delete from public.district_places where district_id = ${sql(district)};
delete from public.district_residences where district_id = ${sql(district)};
delete from public.district_events where district_id = ${sql(district)};

insert into public.district_places (district_id, id, name, kind, x, y, blurb) values
${placeSql};

insert into public.district_activities
  (district_id, id, phase, place_id, name, money, energy, grades, social, hunger, time_slots, risk_or_twist) values
${activitySql};

insert into public.district_residences (district_id, name, type, distance_km, notes) values
${residenceSql};

insert into public.district_events (district_id, id, title, body, choices) values
${eventSql};
`

const out = join(root, 'supabase', 'seed.sql')
writeFileSync(out, sqlText)
console.log(`Wrote ${out} (${places.length} places, ${activities.length} activities, ${residences.length} residences, ${events.length} events)`)
