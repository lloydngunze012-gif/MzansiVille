// Writes the generated score rules (data/campusville/leaderboard.json + activities.csv -> engine/scores.js)
// into supabase/launch.sql, between the SCORE RULES markers.
//   npm run scores-sql           rewrites the block
//   node scripts/scores-sql.mjs --check   exits 1 if the block is stale (npm run check does this)
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { buildDistrict } from '../src/engine/model.js'
import { scoreRules } from '../src/engine/scores.js'
import { cityActivities } from '../src/city/places.js'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const dir = join(root, 'data', 'campusville')
const read = (name) => readFileSync(join(dir, name), 'utf8')

export function load() {
  const district = buildDistrict({
    meta: JSON.parse(read('meta.json')),
    places: read('places.csv'),
    activities: read('activities.csv'),
    houses: JSON.parse(read('houses.json')),
    events: JSON.parse(read('events.json')),
    hours: JSON.parse(read('hours.json')),
    courses: JSON.parse(read('courses.json')),
    besties: JSON.parse(read('besties.json')),
    twists: JSON.parse(read('twists.json')),
    jobs: JSON.parse(read('jobs.json')),
    shop: JSON.parse(read('shop.json')),
    greenway: JSON.parse(read('greenway.json')),
  })
  const config = JSON.parse(read('leaderboard.json'))
  // (City job B: the rows of the open SunnyBay places score by the same defaults)
  return { district, config, rules: scoreRules(district.activities.concat(cityActivities()), config) }
}

export function block(rules, config) {
  const rows = Object.entries(rules).map(([id, r]) => `  ('${id}', '${r.board}', ${r.points}, ${r.limit})`)
  return [
    '-- SCORE RULES START (generated by npm run scores-sql from data/campusville/leaderboard.json: do not edit here)',
    'insert into public.score_rules (activity_id, board, points, daily_limit) values',
    rows.join(',\n'),
    'on conflict (activity_id) do update set board = excluded.board, points = excluded.points, daily_limit = excluded.daily_limit;',
    `delete from public.score_rules where activity_id not in (${Object.keys(rules).map((id) => `'${id}'`).join(', ')});`,
    `insert into public.score_config (key, value) values ('first_badge_week', '${config.firstBadgeWeek}') on conflict (key) do update set value = excluded.value;`,
    '-- SCORE RULES END',
  ].join('\n')
}

const SQL = join(root, 'supabase', 'launch.sql')
const RE = /-- SCORE RULES START[\s\S]*?-- SCORE RULES END/
export function current() {
  const { rules, config } = load()
  const text = readFileSync(SQL, 'utf8')
  return { text, want: block(rules, config), rules }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { text, want, rules } = current()
  if (process.argv.includes('--check')) {
    const have = text.match(RE)?.[0] || ''
    if (have !== want) { console.error('supabase/launch.sql score rules are stale: run npm run scores-sql'); process.exit(1) }
    console.log(`score rules in launch.sql are current (${Object.keys(rules).length} rules)`)
  } else {
    writeFileSync(SQL, text.replace(RE, () => want))
    console.log(`wrote ${Object.keys(rules).length} score rules to supabase/launch.sql`)
  }
}
